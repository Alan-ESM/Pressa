def split_top(s):
    parts, start, depth, quote, esc = [], 0, 0, None, False
    i = 0
    while i < len(s):
        c = s[i]
        if quote:
            if esc: esc = False
            elif c == "\\": esc = True
            elif c == quote:
                if quote == "'" and i + 1 < len(s) and s[i + 1] == "'": i += 1
                else: quote = None
        elif c in "'\"`": quote = c
        elif c == "(": depth += 1
        elif c == ")": depth -= 1
        elif c == "," and depth == 0: parts.append(s[start:i].strip()); start = i + 1
        i += 1
    parts.append(s[start:].strip())
    return [p for p in parts if p]


def convert_strings(s):
    out, i = [], 0
    while i < len(s):
        if s[i] != "'": out.append(s[i]); i += 1; continue
        i += 1; v = []
        while i < len(s):
            c = s[i]
            if c == "'":
                if i + 1 < len(s) and s[i + 1] == "'": v.append("'"); i += 2; continue
                i += 1; break
            if c == "\\" and i + 1 < len(s):
                n = s[i + 1]
                v.append({"0": "\0", "b": "\b", "n": "\n", "r": "\r", "t": "\t", "Z": "\x1a", "\\": "\\", "'": "'", '"': '"'}.get(n, n))
                i += 2; continue
            v.append(c); i += 1
        out.append("'" + "".join(v).replace("'", "''") + "'")
    return "".join(out)


def backticks(s):
    return re.sub(r"`([^`]+)`", r'"\1"', s)


def end_statement(s, start):
    quote, esc, depth = None, False, 0
    for i in range(start, len(s)):
        c = s[i]
        if quote:
            if esc: esc = False
            elif c == "\\": esc = True
            elif c == quote:
                if quote == "'" and i + 1 < len(s) and s[i + 1] == "'": continue
                quote = None
        elif c in "'\"`": quote = c
        elif c == "(": depth += 1
        elif c == ")": depth -= 1
        elif c == ";" and depth == 0: return i
    return len(s)


tables, touch = [], []
auto = set(re.findall(r"ALTER TABLE `([^`]+)`\s+MODIFY `id`[^;]*?AUTO_INCREMENT", src, re.S))
for m in re.finditer(r"CREATE TABLE `([^`]+)`\s*\(", src):
    name, start = m.group(1), m.end()
    if name.startswith("vue_"): continue
    # Match the CREATE TABLE closing parenthesis, ignoring quoted text.
    quote, esc, depth = None, False, 1
    i = start
    while i < len(src) and depth:
        c = src[i]
        if quote:
            if esc: esc = False
            elif c == "\\": esc = True
            elif c == quote: quote = None
        elif c in "'\"`": quote = c
        elif c == "(": depth += 1
        elif c == ")": depth -= 1
        i += 1
    cols, checks, touch_field = [], [], False
    for item in split_top(src[start:i - 1]):
        cm = re.match(r"`([^`]+)`\s+(.*)$", item, re.S)
        if not cm: continue
        col, spec = cm.groups()
        if re.search(r"ON UPDATE current_timestamp", spec, re.I): touch_field = True
        spec = re.sub(r"\s+ON UPDATE current_timestamp\(\)", "", spec, flags=re.I)
        spec = re.sub(r"\b(?:tinyint|smallint|mediumint|int|integer|bigint)\(\d+\)", lambda x: "smallint" if x.group(0).startswith("tinyint") or x.group(0).startswith("smallint") else "integer", spec, flags=re.I)
        spec = re.sub(r"\bdatetime(?:\(\d+\))?", "timestamp", spec, flags=re.I)
        spec = re.sub(r"\btimestamp\(\d+\)", "timestamp", spec, flags=re.I)
        spec = re.sub(r"current_timestamp\(\)", "now()", spec, flags=re.I)
        spec = re.sub(r"\b(longtext|mediumtext|tinytext|text)\b", "text", spec, flags=re.I)
        spec = re.sub(r"text\s+CHARACTER SET utf8mb4\s+COLLATE utf8mb4_bin", "jsonb", spec, flags=re.I)
        spec = re.sub(r'CHECK\s*\(json_valid\([`"]+[^`"]+[`"]+\)\)', "", spec, flags=re.I)
        if col == "uuid":
            spec = re.sub(r"char\(36\)", "uuid", spec, flags=re.I)
            spec = re.sub(r"DEFAULT\s+uuid\(\)", "DEFAULT gen_random_uuid()", spec, flags=re.I)
        spec = re.sub(r"`([^`]+)`", r'"\1"', spec)
        em = re.search(r"enum\((.*?)\)", spec, re.I | re.S)
        if em:
            vals = em.group(1)
            if name == "communications" and col == "canal": vals = "'sms','email','appel','interne'"
            if name == "communications" and col == "statut": vals = "'prepare','envoye','envoye_manuellement','echec','annule'"
            spec = spec[:em.start()] + "text" + spec[em.end():]
            checks.append((col, vals))
        spec = re.sub(r"\bunsigned\b", "", spec, flags=re.I)
        spec = re.sub(r"\s+", " ", spec).strip()
        if col == "id" and name in auto: spec += " GENERATED BY DEFAULT AS IDENTITY"
        for enum_col, vals in list(checks):
            if enum_col == col:
                spec += f' CHECK ("{col}" IN ({vals}))'
                checks.remove((enum_col, vals))
        cols.append(f'"{col}" {spec}')
    tables.append((name, f'CREATE TABLE "{name}" (\n  ' + ",\n  ".join(cols) + "\n);", touch_field))
    if touch_field: touch.append(name)

indexes, fks = [], []
for m in re.finditer(r"ALTER TABLE `([^`]+)`\s+(.*?);", src, re.S):
    name, clauses = m.groups()
    if "ADD " not in clauses: continue
    for c in split_top(clauses):
        c = re.sub(r"^ADD\s+", "", c, flags=re.I).strip()
        if re.match(r"PRIMARY KEY", c, re.I): indexes.append(f'ALTER TABLE "{name}" ADD {backticks(c)};')
        elif re.match(r"UNIQUE KEY", c, re.I):
            x = re.match(r"UNIQUE KEY `([^`]+)`\s*\((.*)\)", c, re.I | re.S)
            if x: indexes.append(f'CREATE UNIQUE INDEX "{name}_{x.group(1)}" ON "{name}" ({backticks(x.group(2))});')
        elif re.match(r"KEY", c, re.I):
            x = re.match(r"KEY `([^`]+)`\s*\((.*)\)", c, re.I | re.S)
            if x: indexes.append(f'CREATE INDEX "{name}_{x.group(1)}" ON "{name}" ({backticks(x.group(2))});')
        elif re.match(r"CONSTRAINT", c, re.I):
            c = backticks(c)
            fks.append(f'ALTER TABLE "{name}" ADD {c} DEFERRABLE INITIALLY DEFERRED;')

schema = ["-- Converted from pressa.sql: MariaDB to PostgreSQL/Supabase.", "CREATE EXTENSION IF NOT EXISTS pgcrypto;"]
schema += [t[1] for t in tables] + indexes + fks
